#!/usr/bin/env python3
"""Render Open WebUI .env snippets for bearer-secured forge-gateway + bridge connections."""
from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

try:
    import yaml
except ImportError:
    print("render-forge-llm-openwebui-env: pip install pyyaml", file=sys.stderr)
    raise SystemExit(2)


def _load_manifest(path: Path) -> dict:
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


def _read_bearer(bearer_file: Path) -> str:
    if not bearer_file.is_file():
        return ""
    for line in bearer_file.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line.startswith("FORGE_LLM_GATEWAY_BEARER="):
            return line.split("=", 1)[1].strip().strip('"').strip("'")
    return ""


def _bridge_bearer(bearer_dir: Path, slug: str) -> str:
    env_path = bearer_dir / f"bridge-{slug}.env"
    if not env_path.is_file():
        return ""
    for line in env_path.read_text(encoding="utf-8").splitlines():
        if line.startswith("FORGE_WEB_BRIDGE_BEARER="):
            return line.split("=", 1)[1].strip()
    return ""


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument(
        "--manifest",
        type=Path,
        default=Path(__file__).resolve().parent.parent / "config" / "forge-llm-granite-openwebui.yaml",
    )
    ap.add_argument(
        "--bearer-file",
        type=Path,
        default=Path.home() / ".config" / "forge-open-webui" / "forge-llm-gateway.env",
    )
    ap.add_argument(
        "--bearer-dir",
        type=Path,
        default=Path.home() / ".config" / "forge-open-webui",
    )
    ap.add_argument("--gateway-port", type=int, default=int(os.environ.get("FORGE_GATEWAY_HOST_PORT", "18080")))
    ap.add_argument("--json", action="store_true", help="Print JSON for automation")
    args = ap.parse_args()

    manifest = _load_manifest(args.manifest)
    gw = manifest.get("gateway") or {}
    gw_url = f"http://host.docker.internal:{args.gateway_port}/v1"
    gw_bearer = _read_bearer(args.bearer_file)
    urls: list[str] = [gw_url]
    keys: list[str] = [gw_bearer]

    for bridge in manifest.get("external_bridges") or []:
        slug = str(bridge.get("slug") or "").strip()
        if not slug:
            continue
        port = 9240 if "chatgpt" in slug else 9241 if "gemini" in slug else None
        if port is None:
            continue
        bearer = _bridge_bearer(args.bearer_dir, slug)
        if not bearer:
            continue
        urls.append(f"http://host.docker.internal:{port}/v1")
        keys.append(bearer)

    payload = {
        "OPENAI_API_BASE_URLS": ";".join(urls),
        "OPENAI_API_KEYS": ";".join(keys),
        "ENABLE_OPENAI_API": "true",
        "ENABLE_OLLAMA_API": "false",
        "GATEWAY_AUTH_REQUIRED": "true",
        "FORGE_LLM_EXPOSE_PINNED_MODELS_ONLY": "true",
        "gateway_bearer_configured": bool(gw_bearer),
        "models": manifest.get("models") or [],
        "connection_label": gw.get("connection_label") or "forge-llm-granite",
    }

    if args.json:
        print(json.dumps(payload, indent=2))
        return

    print("# Generated by render-forge-llm-openwebui-env.py — do not commit secrets")
    print(f"OPENAI_API_BASE_URLS={payload['OPENAI_API_BASE_URLS']}")
    print(f"OPENAI_API_KEYS={'<set-forge-llm-gateway-bearer>' if not gw_bearer else '<redacted>'}")
    print("ENABLE_OPENAI_API=true")
    print("ENABLE_OLLAMA_API=false")
    print("")
    print("# forge-llm-control-plane/.env (same bearer as first OPENAI_API_KEY slot)")
    print("GATEWAY_AUTH_REQUIRED=true")
    print(f"FORGE_API_TOKEN={'<same-as-FORGE_LLM_GATEWAY_BEARER>' if gw_bearer else '<run-install-script>'}")
    print("FORGE_LLM_EXPOSE_PINNED_MODELS_ONLY=true")
    print("")
    print("# Models exposed in Open WebUI (pick in chat; gateway routes by model id):")
    for m in payload["models"]:
        print(f"#   {m.get('id')} — {m.get('label')} (forge_task={m.get('forge_task')})")


if __name__ == "__main__":
    main()
